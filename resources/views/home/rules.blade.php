        <h1>⚔️ FMJ oGame — Server Rules</h1>
        <p class="subtitle">Last updated: July 2026 · Violations may result in warnings, bans, or account deletion.</p>

        <h2>1. No Multi-Accounts</h2>
        <p>Each player is allowed <span class="highlight">one account per server</span>. Creating or using multiple accounts is strictly prohibited. This includes:</p>
        <ul>
            <li>Registering more than one account from the same IP or household without prior admin approval</li>
            <li>Using another player's account</li>
            <li>Creating "farms" or feeder accounts</li>
        </ul>
        <p>If multiple people in the same household want to play, contact an admin first.</p>

        <h2>2. No Pushing</h2>
        <p>"Pushing" means deliberately sending resources to another account to give them an unfair advantage. This includes:</p>
        <ul>
            <li>Repeatedly losing fleets on purpose to transfer resources</li>
            <li>Sending resources via transport missions to boost another player</li>
            <li>Using market trades at inflated prices to move resources</li>
        </ul>
        <p>Normal fleet crashes and legitimate trades between active players are fine.</p>

        <h2>3. No Bug Exploitation</h2>
        <p>If you find a bug or exploit, <span class="highlight">report it to an admin immediately</span>. Using bugs to gain an advantage is forbidden. Players who report bugs responsibly may be rewarded.</p>

        <h2>4. No Offensive Behaviour</h2>
        <p>Keep it respectful. The following are not tolerated:</p>
        <ul>
            <li>Racism, sexism, or hate speech</li>
            <li>Harassment or targeted abuse of other players</li>
            <li>Threats of real-world violence</li>
            <li>Excessive swearing directed at individuals</li>
        </ul>
        <p>Trash talk and friendly rivalry are part of the game. Just don't cross the line.</p>

        <h2>5. No Account Sharing or Selling</h2>
        <p>Accounts are personal and non-transferable. You may not:</p>
        <ul>
            <li>Share your login credentials with other players</li>
            <li>Sell, trade, or give away your account</li>
            <li>Buy or receive accounts from other players</li>
        </ul>

        <h2>6. No Automation (Unless Approved)</h2>
        <p>Using scripts, bots, or automated tools to play the game is <span class="warning">forbidden</span> unless the server explicitly allows it. This includes:</p>
        <ul>
            <li>Auto-farming scripts</li>
            <li>Auto-build or auto-research bots</li>
            <li>Fleet-saving scripts</li>
            <li>Any tool that interacts with the game automatically</li>
        </ul>

        <h2>7. Vacation Mode</h2>
        <p>Vacation mode is there to protect you when you're away. Rules:</p>
        <ul>
            <li>Minimum 48 hours before vacation mode activates</li>
            <li>You cannot attack or be attacked while in vacation mode</li>
            <li>Production stops while in vacation mode</li>
            <li>Do not abuse vacation mode to dodge incoming attacks</li>
        </ul>

        <h2>8. Inactive Account Cleanup</h2>
        <p>Accounts inactive for more than <span class="highlight">30 days</span> may be deleted or given to new players. Admins will try to notify you before cleanup.</p>

        <h2>9. Admin Decisions</h2>
        <p>Admin decisions are final. If you believe a decision was unfair, you can appeal by contacting the admin team, but harassment of admins will not be tolerated.</p>

        <h2>10. Have Fun</h2>
        <p>It's a game. Play hard, fight smart, make allies, betray them later (in-game only 😈). Just follow the rules and everyone has a good time.</p>

